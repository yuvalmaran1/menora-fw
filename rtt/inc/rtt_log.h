#ifndef RTT_LOG_H_
#define RTT_LOG_H_
/******************************************************************************
 * Includes
 *****************************************************************************/
#include <stdint.h>
#include <stdarg.h>

/******************************************************************************
 * Constants
 *****************************************************************************/

/******************************************************************************
 * Macros
 *****************************************************************************/

/******************************************************************************
 * Data types
 *****************************************************************************/
/* log level enumeration */
typedef enum
{
    RTT_CRITICAL  = 0,
    RTT_ERROR     = 1,
    RTT_WARNING   = 2,
    RTT_INFO      = 3,
    RTT_DEBUG     = 4,
    RTT_TRACE     = 5
} RTT_LOG_LEVEL_en;

/******************************************************************************
 * Public function prototypes
 *****************************************************************************/
/***************************************************************************//**
 * Initialize module
 *
 * @return none
 ******************************************************************************/
void RTT_LOG_init(void);

/***************************************************************************//**
 * Emit log
 * 
 * @param[in] level log level from @ref RTT_LOG_LEVEL_en
 * @param[in] source log source (module/file/etc.)
 * @param[in] msg log message string
 *
 * @return none
 ******************************************************************************/
void RTT_LOG_log(RTT_LOG_LEVEL_en level, const char* source, const char* msg, ...);

#endif // RTT_LOG_H_